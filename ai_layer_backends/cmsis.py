"""Render a CMSIS AI layer from the shared MLOps description and export."""

import os
from pathlib import Path
import re
import xml.etree.ElementTree as ET

from . import ExportedModel, selected_symbols

PACK = "PyTorch::ExecuTorch"


def pack_root() -> Path:
    """The CMSIS pack root: $CMSIS_PACK_ROOT, else cpackget's default."""
    if env := os.environ.get("CMSIS_PACK_ROOT"):
        return Path(env)
    if os.name == "nt":
        return Path(os.environ.get("LOCALAPPDATA", Path.home() / "AppData/Local")) / "Arm/Packs"
    return Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "arm/packs"


def executorch_version(mlops_file: Path) -> str:
    """Read the ExecuTorch pack version selected in the adjacent pack lock file."""
    import yaml

    pack_file = mlops_file.with_name(mlops_file.name.replace(".cbuild-mlops.yml", ".cbuild-pack.yml"))
    fallback = None
    for entry in yaml.safe_load(pack_file.read_text())["cbuild-pack"]["resolved-packs"]:
        name, _, version = entry["resolved-pack"].partition("@")
        selectors = entry.get("selected-by-pack", [])
        if name != PACK or not selectors:
            continue
        if f"{PACK}@{version}" in selectors:
            return version
        fallback = fallback or version
    if fallback:
        return fallback
    raise ValueError(f"{pack_file}: {PACK} is not among the resolved packs")


def components(model: ExportedModel, pack: Path) -> tuple[list[str], list[str]]:
    """Select exact operator components from the pack's registration and PDSC."""
    manifest = ET.parse(pack / "PyTorch.ExecuTorch.pdsc")
    labels = {}
    for component in manifest.findall('./components/component[@Cgroup="ExecuTorch Operators"]'):
        for symbol in re.findall(r"RTE_ML_EXECUTORCH_OP_([A-Z0-9_]+)", component.findtext("RTE_Components_h", "")):
            labels[symbol] = component.attrib["Csub"]
    symbols = selected_symbols(
        model.operators,
        (pack / "src/registration/RegisterAllKernels.cpp").read_text(),
        "RTE_ML_EXECUTORCH_OP_",
    )
    missing = set(symbols) - labels.keys()
    if missing:
        raise ValueError(f"pack components missing for {sorted(missing)}")
    return ["Runtime", "Kernel Utils", "Kernel Registration", "Backend EthosU"], sorted(labels[s] for s in symbols)


def clayer(mlops: dict, runtime: list[str], operators: list[str], mlops_file: Path, version: str) -> str:
    lines = [
        f"# Generated by create_ai_layer.py from {mlops_file.name} -- do not edit.",
        f"# Re-run `python create_ai_layer.py {mlops_file.name}` after changing",
        "# model/model.py or the csolution's mlops: node.",
        "layer:",
        "  type: AI",
        f"  description: {mlops.get('description', mlops['model'].get('name', 'AI layer'))}",
        "",
        "  packs:",
        f"    - pack: {PACK}@{version}",
        "",
        "  define:",
        "    - ET_LOG_ENABLED: 0",
        "",
        "  add-path:",
        "    - .",
        "",
        "  components:",
        *[f"    - component: Machine Learning:ExecuTorch:{c}" for c in runtime],
        *[f"    - component: Machine Learning:ExecuTorch Operators:{c}" for c in operators],
        "",
        "  groups:",
        f"    - group: {mlops['model'].get('name', 'Model')}",
        "      files:",
        "        - file: ./model_pte.c",
        "        - file: ./model_pte.h",
        "",
    ]
    return "\n".join(lines)


def render(mlops_file: Path, mlops: dict, model: ExportedModel) -> tuple[Path, dict[str, str]]:
    """Return the layer path and metadata files without writing them."""
    version = executorch_version(mlops_file)
    vendor, _, pack = PACK.partition("::")
    runtime, operators = components(model, pack_root() / vendor / pack / version)
    layer_file = mlops_file.parent / mlops["model"].get("clayer", "ai_layer/ai_layer.clayer.yml")
    return layer_file, {layer_file.name: clayer(mlops, runtime, operators, mlops_file, version)}
